// Compiles src/assets/logos/*.svg into src/data/logos.generated.ts so marks ship inside the
// page with no extra network requests. Run with: node scripts/build-logos.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const TITLES = {
  angular: 'Angular', aws: 'AWS', azure: 'Azure', carleton: 'Carleton University', chartdotjs: 'Chart.js', claude: 'Claude', cplusplus: 'C++', csharp: 'C#', css: 'CSS', cursor: 'Cursor', docker: 'Docker', dotnet: '.NET', elevenlabs: 'ElevenLabs', expo: 'Expo', express: 'Express', fastapi: 'FastAPI', firebase: 'Firebase', githubactions: 'GitHub Actions', googlegemini: 'Gemini', html5: 'HTML5', ibm: 'IBM', java: 'Java', jonas: 'Jonas Software', langchain: 'LangChain', mapbox: 'Mapbox', microsoft: 'Microsoft', nestjs: 'NestJS', netlify: 'Netlify', nextdotjs: 'Next.js', nodedotjs: 'Node.js', openai: 'OpenAI', postgresql: 'PostgreSQL', pytest: 'pytest', python: 'Python', railway: 'Railway', react: 'React', redhatopenshift: 'OpenShift', slack: 'Slack', springboot: 'Spring Boot', sqlalchemy: 'SQLAlchemy', stripe: 'Stripe', supabase: 'Supabase', tailwindcss: 'Tailwind CSS', twilio: 'Twilio', typeorm: 'TypeORM', typescript: 'TypeScript', vapi: 'Vapi', javascript: 'JavaScript', shadcnui: 'shadcn/ui',
};
const dir = 'src/assets/logos/';
const logos = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(dir + file, 'utf8');
  const key = file.replace('.svg', '');
  const line = key.startsWith('glyph-');
  if (!line && !TITLES[key]) throw new Error(`no title for ${key}`);
  if (/<script|on\w+=/i.test(svg)) throw new Error(`unsafe svg ${file}`);
  logos[key] = {
    title: line ? '' : TITLES[key],
    viewBox: svg.match(/viewBox="([^"]+)"/)[1],
    inner: svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>')),
    color: svg.match(/fill="(#[0-9a-fA-F]{6})"/)?.[1] ?? '#EFEDE8',
    line,
  };
}
writeFileSync('src/data/logos.generated.ts', `// Generated by scripts/build-logos.mjs. Do not edit by hand.\nexport const LOGO_DATA = ${JSON.stringify(logos, null, 1)} as const;\n`);
console.log(`[logos] wrote ${Object.keys(logos).length} marks`);
